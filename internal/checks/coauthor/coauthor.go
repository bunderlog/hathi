// Package coauthor is the Check no-ai-coauthor.
package coauthor

import (
	"regexp"
	"strings"

	"github.com/bunderlog/hathi/internal/checks"
)

var (
	// An AI named in a co-author trailer or a credit line: Claude with a model, Code or its email,
	// or a coding agent by a name or an email no person has.
	ai = regexp.MustCompile(
		`(?i)\bclaude (code|opus|sonnet|haiku|fable|\d)|@anthropic\.com|` +
			`\bcopilot\b|\bcursor agent\b|@cursor\.(com|sh)|\bchatgpt\b|\bcodex\b|@openai\.com|` +
			`\bgemini\b|devin-ai-integration|\baider\b|@ampcode\.com`)
	// A co-author trailer, with the co-author's name; \s is ASCII's, \v too, as in `baloo`.
	coauthor = regexp.MustCompile(`(?i)^[\t-\r ]*co-authored-by:[\t-\r ]*([^<]*?)[\t-\r ]*(<|$)`)
	// A line crediting a tool with the commit: `Generated with …`, `🤖 Generated by …`.
	credit = regexp.MustCompile(`(?i)^[\t-\r ]*(🤖[\t-\r ]*)?generated (with|by)[\t-\r ]`)
	robot  = regexp.MustCompile(`^[\t-\r ]*🤖`)
	claude = regexp.MustCompile(`(?i)\bclaude\b`)
)

// Check is no-ai-coauthor: each line of the commit message that makes an AI its co-author or
// credits one with it. A person's co-author trailer passes, even one named Claude with a surname;
// a co-author named only Claude is the AI. In a credit line a bare Claude is the AI too, since a
// person generates no commit, and the robot always marks one. A message Git writes itself is
// checked too.
var Check = checks.Check{
	Name:    "no-ai-coauthor",
	Hook:    "commit-msg",
	Explain: explanation,
	Find: func(in checks.Input) ([]checks.Finding, error) {
		var found []checks.Finding
		for i, line := range strings.Split(checks.AboveScissors(in.Message), "\n") {
			m := coauthor.FindStringSubmatch(line)
			switch {
			case m != nil && (ai.MatchString(line) || strings.ToLower(m[1]) == "claude"):
			case m == nil && credit.MatchString(line) &&
				(ai.MatchString(line) || claude.MatchString(line) || robot.MatchString(line)):
			default:
				continue
			}
			found = append(found, checks.Finding{Line: i + 1, Reason: line})
		}
		return found, nil
	},
}

// explanation is what `hathi explain` prints for the Check: what it looks for, how to fix a
// failure, and how to mark a false alarm.
const explanation = `no-ai-coauthor (commit-msg) looks for a line of the commit message that
makes an AI its co-author, a Co-authored-by trailer naming Claude, Copilot, Cursor, Codex, Gemini,
Devin, Aider or Amp, or credits one with it, such as "Generated with Claude Code". A person's
Co-authored-by passes, even one named Claude with a surname.

To fix it, remove the line: git commit --amend for the last commit, git rebase -i for an older one.
Claude Code adds its own unless its settings turn attribution off.

no-ai-coauthor: false in .hathi.yml turns it off.
`
